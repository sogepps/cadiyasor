/**
 * Copies every finished translation into the app and regenerates the registries that list them.
 *
 *   node tools/tx/generate.cjs
 *
 * English and Turkish content come straight from tools/tx/src/catalog.json. Any other locale is
 * only taken when it passes the validator; anything unfinished is skipped and the app falls back
 * to English for it. Coordinator only: translators never run this.
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..', '..');
const TX = __dirname;
const sets = Object.keys(JSON.parse(fs.readFileSync(path.join(TX, 'sets.json'), 'utf8')));
const catalog = JSON.parse(fs.readFileSync(path.join(TX, 'src/catalog.json'), 'utf8'));
const LISTS = ['answers', 'ball', 'omens', 'questions'];

const passes = (set, what) => {
  try {
    execFileSync(process.execPath, [path.join(TX, 'validate.cjs'), set, what], { stdio: 'pipe' });
    return true;
  } catch {
    return false;
  }
};

const contentDir = path.join(ROOT, 'src/content/locales');
const uiDir = path.join(ROOT, 'src/i18n/ui');
fs.mkdirSync(contentDir, { recursive: true });

for (const lang of ['en', 'tr']) {
  const content = Object.fromEntries(LISTS.map((l) => [l, catalog[l].map((x) => x[lang])]));
  fs.writeFileSync(path.join(contentDir, `${lang}.json`), JSON.stringify(content, null, 1) + '\n');
}

const contentSets = ['en', 'tr'];
const uiSets = ['en', 'tr'];
const skipped = [];

for (const set of sets) {
  const content = path.join(TX, `out/${set}/content.json`);
  if (fs.existsSync(content) && passes(set, 'content')) {
    fs.copyFileSync(content, path.join(contentDir, `${set}.json`));
    contentSets.push(set);
  } else skipped.push(`${set}:content`);

  const ui = path.join(TX, `out/${set}/ui.json`);
  if (fs.existsSync(ui) && passes(set, 'ui')) {
    fs.copyFileSync(ui, path.join(uiDir, `${set}.json`));
    uiSets.push(set);
  } else skipped.push(`${set}:ui`);
}

const header = '// Generated by tools/tx/generate.cjs — do not edit by hand.\n';
const registry = (name, type, dir, codes) =>
  `${header}import type { LocaleCode } from '${type}';\n\n` +
  `export const ${name}: Partial<Record<LocaleCode, () => unknown>> = {\n` +
  codes.map((c) => `  '${c}': () => require('./${dir}/${c}.json'),`).join('\n') +
  '\n};\n';

fs.writeFileSync(path.join(ROOT, 'src/content/content.gen.ts'), registry('CONTENT_SETS', '../i18n/languages', 'locales', contentSets));
fs.writeFileSync(path.join(ROOT, 'src/i18n/dictionaries.gen.ts'), registry('DICTIONARIES', './languages', 'ui', uiSets));
fs.writeFileSync(
  path.join(ROOT, 'src/content/tones.gen.ts'),
  `${header}import type { Tone } from './types';\n\n` +
    `/** Tone of every answer, in catalog order (${catalog.answers.length} answers). */\n` +
    `export const ANSWER_TONES: readonly Tone[] = ${JSON.stringify(catalog.answers.map((a) => a.tone))};\n\n` +
    `/** Tone of every crystal-ball answer (${catalog.ball.length}). */\n` +
    `export const BALL_TONES: readonly Tone[] = ${JSON.stringify(catalog.ball.map((a) => a.tone))};\n`,
);

console.log(`content sets: ${contentSets.length} · ui dictionaries: ${uiSets.length} · answers: ${catalog.answers.length}`);
if (skipped.length) console.log(`skipped (unfinished or failing): ${skipped.join(' ')}`);
